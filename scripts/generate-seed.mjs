/**
 * Builds supabase/seed.sql from the config files, so a fresh Supabase project starts with exactly
 * the content the site shows today. Re-run after editing src/config/* for a new client:
 *
 *   npm run seed:generate
 *
 * The seed is safe to run more than once: each table is only filled if it is still empty
 * (categories/services by slug), so it never duplicates or overwrites the owner's edits.
 */
import { writeFileSync } from "node:fs";
import { bookingConfig } from "../src/config/booking.config.ts";
import { contentConfig } from "../src/config/content.config.ts";
import { faq } from "../src/config/faq.config.ts";
import { gallery } from "../src/config/gallery.config.ts";
import { packages } from "../src/config/packages.config.ts";
import { serviceCategories, services } from "../src/config/services.config.ts";
import { siteConfig } from "../src/config/site.config.ts";
import { team } from "../src/config/team.config.ts";
import { testimonials } from "../src/config/testimonials.config.ts";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const textArray = (arr) => (arr.length ? `array[${arr.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const dateArray = (arr) => (arr.length ? `array[${arr.map(q).join(", ")}]::date[]` : "'{}'::date[]");
const bool = (v) => (v ? "true" : "false");

/** Insert rows only when the table is still empty. */
function fillIfEmpty(table, columns, rows) {
  if (!rows.length) return "";
  const values = rows.map((r) => `      (${r.join(", ")})`).join(",\n");
  return `do $$ begin
  if not exists (select 1 from public.${table}) then
    insert into public.${table} (${columns.join(", ")}) values
${values};
  end if;
end $$;
`;
}

const social = (platform) => siteConfig.socials.find((s) => s.platform === platform)?.url ?? "";
const c = siteConfig.contact;
const out = [];

out.push(`-- ════════════════════════════════════════════════════════════════════
--  Seed data — generated by scripts/generate-seed.mjs from src/config/*.
--  Run once after both migrations (SQL Editor → paste → Run). Safe to re-run.
--  Do not edit by hand: change the config files and run \`npm run seed:generate\`.
-- ════════════════════════════════════════════════════════════════════
`);

// Site settings (single row)
out.push(`insert into public.site_settings (
  id, business_name, short_name, tagline, description, phone, whatsapp, email, address,
  maps_embed_url, maps_link, instagram_url, facebook_url, youtube_url, opening_hours, breaks,
  holidays, theme, logo_url, hero, seo_title, seo_description, sections
) values (
  1, ${q(siteConfig.fullName)}, ${q(siteConfig.name)}, ${q(siteConfig.tagline)}, ${q(siteConfig.description)},
  ${q(c.phone)}, ${q(c.whatsapp)}, ${q(c.email)}, ${json(c.address)},
  ${q(c.mapsEmbedUrl)}, ${q(c.mapsLink)}, ${q(social("instagram"))}, ${q(social("facebook"))}, ${q(social("youtube"))},
  ${json(bookingConfig.weeklyHours)}, ${json(bookingConfig.breaks)}, ${dateArray(bookingConfig.holidays)},
  ${q(siteConfig.theme)}, ${q(siteConfig.logo?.src ?? null)},
  ${json({
    eyebrow: contentConfig.hero.eyebrow,
    headlineLines: contentConfig.hero.headlineLines,
    subheading: contentConfig.hero.subheading,
    primaryCta: contentConfig.hero.primaryCta,
    secondaryCta: contentConfig.hero.secondaryCta,
  })},
  ${q(siteConfig.seo.defaultTitle)}, ${q(siteConfig.description)}, ${json(siteConfig.sections)}
) on conflict (id) do nothing;
`);

// Categories + services (keyed by slug, so re-running only adds missing ones)
out.push(`insert into public.service_categories (slug, name, sort_order) values
${serviceCategories.map((cat, i) => `  (${q(cat.id)}, ${q(cat.label)}, ${i})`).join(",\n")}
on conflict (slug) do nothing;
`);
out.push(`insert into public.services
  (slug, category_id, name, description, price, price_from, duration_min, image_url, image_alt, is_popular, sort_order)
values
${services
  .map(
    (s, i) =>
      `  (${q(s.id)}, (select id from public.service_categories where slug = ${q(s.category)}), ${q(s.name)}, ${q(
        s.description,
      )}, ${s.price}, ${bool(s.priceFrom)}, ${s.durationMinutes}, ${q(s.image.src)}, ${q(s.image.alt)}, ${bool(
        s.popular,
      )}, ${i})`,
  )
  .join(",\n")}
on conflict (slug) do nothing;
`);

out.push(
  fillIfEmpty(
    "packages",
    ["name", "tagline", "price", "price_from", "price_note", "features", "is_highlighted", "cta_label", "sort_order"],
    packages.map((p, i) => [
      q(p.name), q(p.tagline), p.price, bool(p.priceFrom), q(p.priceNote ?? ""), textArray(p.features),
      bool(p.highlighted), q(p.ctaLabel), i,
    ]),
  ),
);

const o = contentConfig.offers;
out.push(
  fillIfEmpty(
    "offers",
    ["title", "subtitle", "discount_text", "code", "cta_label", "start_date", "end_date", "is_active", "show_countdown"],
    [[q(o.title), q(o.description), q(o.eyebrow), q(o.code ?? ""), q(o.ctaLabel), "now()", q(o.endsAt), bool(siteConfig.sections.offers), "true"]],
  ),
);

out.push(
  fillIfEmpty(
    "gallery_items",
    ["title", "image_url", "image_alt", "before_image_url", "size", "sort_order"],
    gallery.map((g, i) =>
      g.type === "image"
        ? [q(g.caption ?? ""), q(g.image.src), q(g.image.alt), "null", q(g.size), i]
        : [q(g.caption), q(g.after.src), q(g.after.alt), q(g.before.src), q(g.size), i],
    ),
  ),
);

out.push(
  fillIfEmpty(
    "testimonials",
    ["name", "location", "service", "text", "rating", "sort_order"],
    testimonials.map((t, i) => [q(t.name), q(t.location ?? ""), q(t.service ?? ""), q(t.quote), t.rating, i]),
  ),
);

out.push(
  fillIfEmpty(
    "team_members",
    ["name", "role", "specialty", "photo_url", "photo_alt", "instagram_url", "sort_order"],
    team.map((m, i) => [q(m.name), q(m.role), q(m.specialty), q(m.image.src), q(m.image.alt), q(m.instagram ?? ""), i]),
  ),
);

out.push(fillIfEmpty("faqs", ["question", "answer", "sort_order"], faq.map((f, i) => [q(f.question), q(f.answer), i])));

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.filter(Boolean).join("\n"));
console.log("supabase/seed.sql written.");
